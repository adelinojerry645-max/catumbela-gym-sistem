CREATE OR REPLACE FUNCTION public.adicionar_item_colecao(p_chave text, p_item jsonb)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
BEGIN
  INSERT INTO estado_app (chave, valor, atualizado_em)
  VALUES (p_chave, jsonb_build_array(p_item), now())
  ON CONFLICT (chave) DO UPDATE
  SET valor = estado_app.valor || p_item, atualizado_em = now();
END;
$function$;

CREATE OR REPLACE FUNCTION public.atualizar_item_colecao(p_chave text, p_id text, p_patch jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
AS $function$
declare n int;
begin
  update estado_app
     set valor = (select coalesce(jsonb_agg(case when e->>'id' = p_id then e || p_patch else e end order by ord), '[]'::jsonb)
                    from jsonb_array_elements(valor) with ordinality as t(e, ord)),
         atualizado_em = now()
   where chave = p_chave and jsonb_typeof(valor) = 'array';
  get diagnostics n = row_count;
  return n > 0;
end $function$;

CREATE OR REPLACE FUNCTION public.estado_app_proteger()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  n_antigo int;
  n_novo int;
begin
  if jsonb_typeof(old.valor) = 'array' and jsonb_typeof(new.valor) = 'array' then
    n_antigo := jsonb_array_length(old.valor);
    n_novo := jsonb_array_length(new.valor);

    -- Regra antiga: não deixa a lista cair para menos de metade
    if n_antigo >= 30 and n_novo < n_antigo * 0.5 then
      raise exception 'Bloqueado: a lista % ia passar de % para % itens', new.chave, n_antigo, n_novo;
    end if;

    -- Regra nova: na lista de atletas, não deixa desaparecer mais de 5 de uma vez
    if new.chave = 'membros' and n_antigo >= 30 and (n_antigo - n_novo) > 5 then
      raise exception 'Bloqueado: a lista de atletas ia perder % atletas de uma vez', (n_antigo - n_novo);
    end if;
  end if;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.fazer_copia_seguranca()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  insert into public.copias_seguranca (dados)
  select jsonb_object_agg(chave, valor) from public.estado_app where chave not like 'teste\_%';
  delete from public.copias_seguranca where criado_em < now() - interval '30 days';
end;
$function$;

CREATE OR REPLACE FUNCTION public.gerar_documento_atomico(p_chave text, p_prefixo text, p_ano text, p_documento_sem_numero jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
  lista_atual JSONB;
  maior_numero INT := 0;
  numero_gerado TEXT;
  documento_completo JSONB;
  elem JSONB;
  sufixo TEXT;
  n INT;
BEGIN
  SELECT valor INTO lista_atual FROM estado_app WHERE chave = p_chave FOR UPDATE;
  IF lista_atual IS NULL THEN
    lista_atual := '[]'::jsonb;
    INSERT INTO estado_app (chave, valor) VALUES (p_chave, lista_atual) ON CONFLICT (chave) DO NOTHING;
  END IF;

  FOR elem IN SELECT * FROM jsonb_array_elements(lista_atual)
  LOOP
    IF (elem->>'tipo') = (p_documento_sem_numero->>'tipo')
       AND (elem->>'numero') LIKE (p_prefixo || '-' || p_ano || '-%') THEN
      sufixo := substring(elem->>'numero' FROM '[0-9]+$');
      IF sufixo IS NOT NULL THEN
        n := sufixo::INT;
        IF n > maior_numero THEN maior_numero := n; END IF;
      END IF;
    END IF;
  END LOOP;

  numero_gerado := p_prefixo || '-' || p_ano || '-' || lpad((maior_numero + 1)::TEXT, 6, '0');
  documento_completo := p_documento_sem_numero || jsonb_build_object('numero', numero_gerado, 'id', numero_gerado);

  UPDATE estado_app SET valor = lista_atual || documento_completo, atualizado_em = now() WHERE chave = p_chave;
  RETURN documento_completo;
END;
$function$;

CREATE OR REPLACE FUNCTION public.gravar_colecao_se_atual(p_chave text, p_valor jsonb, p_esperado timestamp with time zone, p_agora timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
declare atual timestamptz; existe boolean;
begin
  select atualizado_em into atual from estado_app where chave = p_chave for update;
  existe := found;
  if not existe then
    insert into estado_app (chave, valor, atualizado_em) values (p_chave, p_valor, p_agora) on conflict (chave) do nothing;
    if found then return jsonb_build_object('ok', true, 'atualizado_em', p_agora); end if;
    return jsonb_build_object('ok', false);
  end if;
  if p_esperado is not null and atual is not null
     and date_trunc('milliseconds', atual) = date_trunc('milliseconds', p_esperado) then
    update estado_app set valor = p_valor, atualizado_em = p_agora where chave = p_chave;
    return jsonb_build_object('ok', true, 'atualizado_em', p_agora);
  end if;
  return jsonb_build_object('ok', false);
end $function$;

CREATE OR REPLACE FUNCTION public.ler_visitas(p_dias integer DEFAULT 7)
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select coalesce(jsonb_agg(jsonb_build_object('dia', dia, 'pagina', pagina, 'total', total) order by dia desc), '[]'::jsonb)
  from visitas_publicas
  where dia >= (now() at time zone 'Africa/Luanda')::date - greatest(p_dias,1) + 1;
$function$;

CREATE OR REPLACE FUNCTION public.pagina_publica()
 RETURNS jsonb
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
select jsonb_build_object(
  'ginasio', (select jsonb_build_object('morada', valor->>'morada', 'cidade', valor->>'cidade', 'telefone', valor->>'telefone', 'email', valor->>'email') from estado_app where chave = 'dadosGinasio'),
  'planos', coalesce((select jsonb_agg(jsonb_build_object('id', p->'id', 'nome', p->'nome', 'preco', p->'preco', 'duracaoDias', p->'duracaoDias', 'entradas', p->'entradas', 'descricao', p->'descricao', 'foto', p->'foto')) from estado_app e, jsonb_array_elements(e.valor) p where e.chave = 'planos'), '[]'::jsonb),
  'config', (select valor->0 from estado_app where chave = 'paginaPublica' and jsonb_typeof(valor) = 'array')
);
$function$;

CREATE OR REPLACE FUNCTION public.registar_visita(p_pagina text)
 RETURNS void
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  insert into visitas_publicas(dia, pagina, total)
  values ((now() at time zone 'Africa/Luanda')::date, left(coalesce(p_pagina,'?'), 20), 1)
  on conflict (dia, pagina) do update set total = visitas_publicas.total + 1;
$function$;

CREATE OR REPLACE FUNCTION public.remover_item_colecao(p_chave text, p_id text)
 RETURNS boolean
 LANGUAGE plpgsql
AS $function$
declare n int;
begin
  update estado_app
     set valor = (select coalesce(jsonb_agg(e order by ord), '[]'::jsonb)
                    from jsonb_array_elements(valor) with ordinality as t(e, ord)
                   where e->>'id' is distinct from p_id),
         atualizado_em = now()
   where chave = p_chave and jsonb_typeof(valor) = 'array';
  get diagnostics n = row_count;
  return n > 0;
end $function$;

CREATE OR REPLACE FUNCTION public.reservar_atividade_atomico(p_chave text, p_atividade_id bigint, p_capacidade integer, p_item jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
AS $function$
DECLARE
  lista_atual JSONB;
  num_reservas INT;
BEGIN
  SELECT valor INTO lista_atual FROM estado_app WHERE chave = p_chave FOR UPDATE;
  IF lista_atual IS NULL THEN
    lista_atual := '[]'::jsonb;
    INSERT INTO estado_app (chave, valor) VALUES (p_chave, lista_atual) ON CONFLICT (chave) DO NOTHING;
  END IF;

  SELECT count(*) INTO num_reservas
  FROM jsonb_array_elements(lista_atual) elem
  WHERE (elem->>'atividadeId')::bigint = p_atividade_id;

  IF p_capacidade IS NOT NULL AND num_reservas >= p_capacidade THEN
    RETURN jsonb_build_object('ok', false, 'motivo', 'Esta atividade já está com a capacidade máxima cheia.');
  END IF;

  UPDATE estado_app SET valor = lista_atual || p_item, atualizado_em = now() WHERE chave = p_chave;
  RETURN jsonb_build_object('ok', true);
END;
$function$;

-- treino do personal (a ordem importa: "quem" primeiro)
CREATE OR REPLACE FUNCTION public.treino_personal_quem(p_senha text)
 RETURNS text
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select nome from public.personais_treino
  where senha_hash = encode(sha256(convert_to('catumbela-pt:' || coalesce(p_senha,''), 'utf8')), 'hex') limit 1;
$function$;

CREATE OR REPLACE FUNCTION public.treino_personal_validar(p_senha text)
 RETURNS text
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select public.treino_personal_quem(p_senha);
$function$;

CREATE OR REPLACE FUNCTION public.treino_personal_apagar(p_senha text, p_data date, p_sexo text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if public.treino_personal_quem(p_senha) is null then return false; end if;
  delete from public.treino_personal where data = p_data and sexo = p_sexo;
  return true;
end $function$;

CREATE OR REPLACE FUNCTION public.treino_personal_guardar(p_senha text, p_data date, p_sexo text, p_titulo text, p_nota text, p_exercicios jsonb)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare quem text;
begin
  quem := public.treino_personal_quem(p_senha);
  if quem is null then return false; end if;
  if p_sexo not in ('m','f') then return false; end if;
  if jsonb_typeof(p_exercicios) <> 'array' or jsonb_array_length(p_exercicios) > 30 then return false; end if;
  insert into public.treino_personal (data, sexo, titulo, nota, exercicios, personal, atualizado_em)
  values (p_data, p_sexo, left(coalesce(p_titulo,''), 80), left(coalesce(p_nota,''), 400), p_exercicios, quem, now())
  on conflict (data, sexo) do update
    set titulo = excluded.titulo, nota = excluded.nota, exercicios = excluded.exercicios, personal = excluded.personal, atualizado_em = now();
  return true;
end $function$;

CREATE OR REPLACE FUNCTION public.treino_personal_listar()
 RETURNS TABLE(data date, sexo text, titulo text, nota text, exercicios jsonb, personal text)
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select t.data, t.sexo, t.titulo, t.nota, t.exercicios, t.personal
  from public.treino_personal t
  where t.data >= (now() at time zone 'Africa/Luanda')::date - 1
  order by t.data;
$function$;

