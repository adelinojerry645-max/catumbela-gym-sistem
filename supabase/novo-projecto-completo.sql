-- ---------- TABELAS ----------
create table if not exists public.estado_app (
  chave text primary key,
  valor jsonb not null default '[]'::jsonb,
  atualizado_em timestamp without time zone default now()
);

create table if not exists public.estado_app_historico (
  id bigint generated by default as identity primary key,
  chave text not null,
  valor jsonb not null,
  gravado_em timestamptz not null default now()
);
create index if not exists estado_app_historico_chave_idx
  on public.estado_app_historico using btree (chave, gravado_em desc);

create table if not exists public.copias_seguranca (
  id bigint generated by default as identity primary key,
  criado_em timestamptz not null default now(),
  dados jsonb not null
);

create table if not exists public.opinioes (
  id uuid primary key default gen_random_uuid(),
  criado_em timestamptz not null default now(),
  tipo text not null default 'avaliacao'
    check (tipo = any (array['avaliacao','reclamacao','sugestao','elogio'])),
  estrelas integer check (estrelas >= 1 and estrelas <= 5),
  mensagem text check (char_length(mensagem) <= 1200),
  nome text check (char_length(nome) <= 80),
  contacto text check (char_length(contacto) <= 60),
  lida boolean not null default false,
  resposta text
);

create table if not exists public.personais_treino (
  nome text primary key,
  senha_hash text not null
);

create table if not exists public.treino_personal (
  data date not null,
  sexo text not null check (sexo = any (array['m','f'])),
  titulo text not null default '',
  nota text not null default '',
  exercicios jsonb not null default '[]'::jsonb,
  personal text not null default '',
  atualizado_em timestamptz not null default now(),
  primary key (data, sexo)
);

create table if not exists public.visitas_publicas (
  dia date not null,
  pagina text not null,
  total integer not null default 0,
  primary key (dia, pagina)
);

